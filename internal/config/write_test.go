package config

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const sample = `# Shedu configuration — generated by install.sh
LANG=he
DAILY_REPORT_AT=08:00
# CLOUD_KEY=commented-out-stays
TELEGRAM_TOKEN="123:fake"
CLOUD_KEY="shk_old_fakevalue"

# trailing comment
`

func TestSetKeysKeepsCommentsAndOrder(t *testing.T) {
	p := filepath.Join(t.TempDir(), "guard.conf")
	if err := os.WriteFile(p, []byte(sample), 0o644); err != nil {
		t.Fatal(err)
	}
	err := SetKeys(p, map[string]string{"CLOUD_KEY": "shk_new_fakevalue", "CLOUD_URL": "https://api.getshedu.com"})
	if err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(p)
	want := `# Shedu configuration — generated by install.sh
LANG=he
DAILY_REPORT_AT=08:00
# CLOUD_KEY=commented-out-stays
TELEGRAM_TOKEN="123:fake"
CLOUD_KEY="shk_new_fakevalue"

# trailing comment
CLOUD_URL="https://api.getshedu.com"
`
	if string(b) != want {
		t.Errorf("got:\n%s\nwant:\n%s", b, want)
	}
	st, _ := os.Stat(p)
	if st.Mode().Perm() != 0o600 {
		t.Errorf("mode %v, want 0600", st.Mode().Perm())
	}
	c, err := Load(p)
	if err != nil || c.CloudKey != "shk_new_fakevalue" || c.TelegramToken != "123:fake" {
		t.Fatalf("result must parse: %+v %v", c, err)
	}
}

func TestSetKeysRemovesAndCreates(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "guard.conf")
	if err := SetKeys(p, map[string]string{"CLOUD_KEY": "shk_a_fake", "CLOUD_URL": "https://x.example"}); err != nil {
		t.Fatal(err)
	}
	if err := SetKeys(p, map[string]string{"CLOUD_KEY": "", "CLOUD_URL": ""}); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(p)
	if strings.TrimSpace(string(b)) != "" {
		t.Errorf("keys not removed: %q", b)
	}
	entries, _ := os.ReadDir(dir)
	if len(entries) != 1 {
		t.Errorf("temp file left behind: %v", entries)
	}
	if err := SetKeys(p, map[string]string{"BAD KEY": "x"}); err == nil {
		t.Error("invalid key accepted")
	}
	if err := SetKeys(p, map[string]string{"CLOUD_KEY": "a\"b"}); err == nil {
		t.Error("quote in value accepted")
	}
}
